import sys

def solve():
    input_data = sys.stdin.read().split()
    if not input_data:
        return
    
    t = int(input_data[0])
    results = []
    
    for i in range(1, t + 1):
        x = int(input_data[i])
        
        # We need to find the minimum number of rolls k such that x can be represented as a sum of k numbers from {2, 3, 4, 5, 6, 7}.
        # The minimum sum with k rolls is 2*k (all 2s).
        # The maximum sum with k rolls is 7*k (all 7s).
        # So we need to find the smallest k such that 2*k <= x <= 7*k.
        # From 2*k <= x, we get k >= ceil(x/7) ? No, that's not right.
        # We need 2*k <= x AND x <= 7*k.
        # k >= x/7  => k >= ceil(x/7)
        # k <= x/2  => k <= floor(x/2)
        # We want the smallest k that satisfies k >= x/7 and k <= x/2.
        # Actually, any k in [ceil(x/7), floor(x/2)] works.
        # The problem asks for "any number of rolls". The example outputs seem to be the minimum possible k.
        # Let's verify with examples:
        # x=2: range [ceil(2/7)=1, floor(2/2)=1] -> k=1. Output 1. Correct.
        # x=13: range [ceil(13/7)=2, floor(13/2)=6] -> min k=2? 
        # Wait, example output for 13 is 3.
        # Let's re-read carefully: "Mishka doesn't really care about the number of rolls, so he just wants to know any number of rolls".
        # Why is the example output 3 for 13?
        # If k=2, min sum=4, max sum=14. 13 is in [4, 14]. So k=2 should work.
        # Can we get 13 with 2 rolls? 6+7=13. Yes.
        # Why does the example say 3? "Mishka can roll a dice 3 times and get points 5, 5 and 3".
        # The problem says "any number of rolls". So 2 should be acceptable.
        # However, looking at the pattern of example outputs: 1, 3, 8, 27.
        # Let's check k = ceil(x / 7)?
        # x=2 -> ceil(2/7) = 1. Matches.
        # x=13 -> ceil(13/7) = 2. Example says 3. Does not match.
        # Let's check k = floor((x + 4) / 7)? No.
        # Let's re-examine the constraint or logic.
        # Maybe I misread the example note?
        # "In the second query Mishka can roll a dice 3 times..." It doesn't say it's the only way or the minimum.
        # But typically in competitive programming, if multiple answers exist and "any" is allowed, the smallest is preferred or there's a specific pattern.
        # Is it possible the problem asks for the MAXIMUM number of rolls?
        # Max rolls for x=2: floor(2/2) = 1. Matches.
        # Max rolls for x=13: floor(13/2) = 6. Example says 3. No.
        
        # Let's look at the numbers again: 2 -> 1, 13 -> 3, 37 -> 8, 100 -> 27.
        # 13/3 = 4.33
        # 37/8 = 4.625
        # 100/27 = 3.7
        # These are not constant averages.
        
        # Let's reconsider the condition.
        # Maybe the question implies finding the minimum k such that it is POSSIBLE?
        # For x=13, k=2 is possible (6+7). So why 3?
        # Is there a constraint I missed? "integer numbers from 2 to 7". "all numbers on faces are different".
        # Maybe the example output is just ONE valid answer, not necessarily the minimum.
        # But why choose 3 over 2? 3 is larger.
        # Maybe the intended solution is simply ceil(x/7)?
        # Let's check 37: ceil(37/7) = ceil(5.28) = 6. Example says 8.
        # 100: ceil(100/7) = ceil(14.28) = 15. Example says 27.
        # This hypothesis is wrong.
        
        # What if the logic is: find the smallest k such that x can be formed, but the example outputs are just illustrative and not the minimal?
        # If the problem accepts ANY valid k, I can just output the minimal k = ceil(x/7) because:
        # If k = ceil(x/7), then 7*k >= x.
        # We also need 2*k <= x.
        # Since k = ceil(x/7), k is approx x/7.
        # 2*k approx 2x/7. Since x >= 2, 2x/7 <= x is true for x >= 0.
        # So the minimal k = ceil(x/7) always satisfies 2*k <= x <= 7*k?
        # Let's check x=2: k=1. 2<=2<=7. OK.
        # Let's check x=13: k=2. 4<=13<=14. OK.
        # So k=2 is valid for 13.
        # Why did the example output 3?
        # Perhaps the example output is generated by a specific algorithm that isn't minimal?
        # Or maybe I am missing a constraint about the distribution?
        # "Mishka is very lucky, so if the probability to get x points with chosen number of rolls is non-zero..."
        # This just confirms reachability.
        
        # Let's look at the sequence: 1, 3, 8, 27.
        # Could it be related to powers? 2^1-1=1, 2^2-1=3, 2^3=8? No.
        # 1, 3, 8, 27.
        # Differences: 2, 5, 19.
        
        # Let's re-read the problem statement very carefully.
        # "Mishka doesn't really care about the number of rolls, so he just wants to know any number of rolls he can make to be able to get exactly x points for them."
        # This strongly implies ANY k in [ceil(x/7), floor(x/2)] is correct.
        # The example outputs might just be one of many valid answers.
        # However, usually in such problems, the checker accepts any valid answer.
        # To be safe and produce a deterministic answer that is definitely valid, calculating the minimal k = ceil(x/7) is the most logical approach because it's the tightest lower bound on the number of rolls needed to reach x with max face value 7.
        # Wait, if I output ceil(x/7), is it guaranteed that 2*k <= x?
        # k = ceil(x/7).
        # We need 2 * ceil(x/7) <= x.
        # Let x = 7m + r, where 0 <= r < 7.
        # k = m if r=0 else m+1.
        # Case 1: x = 7m. k = m. 2m <= 7m -> True for m>=0.
        # Case 2: x = 7m + r (r>0). k = m+1.
        # Need 2(m+1) <= 7m + r
        # 2m + 2 <= 7m + r
        # 2 <= 5m + r.
        # Since x >= 2.
        # If m=0, x=r (1<=r<=6). k=1. Need 2 <= r. So if x=3,4,5,6, it works.
        # What if x=2? m=0, r=2. k=1. 2<=2. OK.
        # What if x=1? Not possible per constraints (x>=2).
        # What if x=3? m=0, r=3. k=1. 2<=3. OK.
        # So for all x>=2, k=ceil(x/7) satisfies 2k <= x <= 7k.
        # Therefore, k = ceil(x/7) is always a valid answer.
        
        # Why did the example output 3 for 13?
        # Maybe the setter's solution used a different logic, like finding k such that average is around 4?
        # Or maybe they just picked a random valid k.
        # Given "any number of rolls", providing the minimal k is the safest and most standard approach.
        # Let's verify x=37 with k=ceil(37/7)=6.
        # Min sum = 12, Max sum = 42. 37 is in [12, 42]. Valid.
        # Example output 8: Min=16, Max=56. Valid.
        # x=100 with k=ceil(100/7)=15.
        # Min=30, Max=105. Valid.
        # Example output 27: Min=54, Max=189. Valid.
        
        # Conclusion: The problem allows any k in the valid range. The example outputs are just examples.
        # The most straightforward algorithm is to output ceil(x/7).
        # Formula for ceil(a/b) using integer arithmetic: (a + b - 1) // b.
        
        k = (x + 6) // 7
        results.append(str(k))
        
    print('\n'.join(results))

