import sys

def solve():
    input_data = sys.stdin.read().split()
    if not input_data:
        return
    
    iterator = iter(input_data)
    t = int(next(iterator))
    
    results = []
    
    for _ in range(t):
        x1 = int(next(iterator))
        y1 = int(next(iterator))
        x2 = int(next(iterator))
        y2 = int(next(iterator))
        
        if x1 == x2 and y1 == y2:
            results.append(1)
            continue
        
        # Calculate the number of steps down and right
        dx = x2 - x1
        dy = y2 - y1
        
        # The number of different sums in a rectangular grid path from top-left to bottom-right
        # where values are generated by GAZ-GIZ (1, 2, 3, ... filling row by row)
        # is simply the number of steps you can take "diagonally" away from the main diagonal path
        # in terms of swapping a 'right' move for a 'down' move earlier.
        # The formula derived for this specific sequence is (dx * dy) + 1.
        
        ans = dx * dy + 1
        results.append(ans)
    
    for res in results:
        print(res)

if __name__ == "__main__":
    solve()