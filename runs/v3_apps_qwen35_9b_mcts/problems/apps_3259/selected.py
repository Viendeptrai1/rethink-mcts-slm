import sys

def solve():
    input = sys.stdin.read
    data = input().split()
    iterator = iter(data)
    
    try:
        N = int(next(iterator))
        Q = int(next(iterator))
    except StopIteration:
        return

    # We need to handle updates and range sum queries.
    # Since N can be up to 10^9, we cannot maintain an array of size N.
    # However, Q is only up to 50,000.
    # The updates are "set range [L, R] to values (k*A) % B".
    # The queries are "sum range [L, R]".
    # This is a classic problem solvable with a Segment Tree over the *time* of updates (or coordinate compression on time),
    # but since the updates overwrite previous values, we can use a "Segment Tree Beats" approach or simply a Segment Tree 
    # where each node stores the latest update covering that range.
    #
    # Actually, a simpler approach for this specific constraint (Q=50000, N=10^9) is to use a Segment Tree where the leaves are not indices 1..N,
    # but rather we map the intervals. However, standard dynamic segment tree or coordinate compression on the endpoints of all queries/updates
    # is the way to go.
    #
    # Let's collect all interesting coordinates: L and R+1 for every update and query.
    # Sort and unique them to get a compressed coordinate space. The number of points will be at most 2*Q.
    # Then build a segment tree over these points.
    #
    # Wait, the update sets values for a range [L, R]. In the compressed space, this range might cover multiple elementary intervals.
    # We can use a standard Segment Tree with Lazy Propagation over the compressed coordinates.
    #
    # Steps:
    # 1. Collect all L and R+1 from all queries (type 1 and type 2).
    # 2. Sort and remove duplicates to create a mapping from original coordinate to index in the compressed array.
    # 3. Build a segment tree over the elementary intervals defined by the compressed coordinates.
    #    The elementary intervals are [coords[i], coords[i+1]-1].
    # 4. Process queries:
    #    - Type 1 (Update): Update the range [L, R] in the segment tree. Since it's an assignment, we use lazy propagation.
    #      The value to set for an elementary interval [start, end] depends on the update parameters (L_upd, R_upd, A, B).
    #      For a specific elementary interval [s, e] fully contained in [L_upd, R_upd], the values are:
    #      val(x) = ((x - L_upd + 1) * A) % B for x in [s, e].
    #      We need the sum of these values. This is an arithmetic progression modulo B.
    #      Sum = sum_{x=s}^{e} ((x - L_upd + 1) * A) % B.
    #      Let k = x - L_upd + 1. As x goes from s to e, k goes from (s - L_upd + 1) to (e - L_upd + 1).
    #      Let k_start = s - L_upd + 1, k_end = e - L_upd + 1.
    #      We need sum_{k=k_start}^{k_end} (k * A) % B.
    #      This is A * sum_{k=k_start}^{k_end} (k % B).
    #      The sum of (k % B) for k in [k_start, k_end] can be computed in O(1) using the formula for sum of remainders.
    #    - Type 2 (Query): Query the sum in range [L, R].
    #
    # Helper function: sum_remainders(k_start, k_end, B)
    #   Calculates sum_{k=k_start}^{k_end} (k % B).
    #   Let f(n, B) = sum_{k=0}^{n} (k % B).
    #   Then sum_{k=a}^{b} (k % B) = f(b, B) - f(a-1, B).
    #   f(n, B):
    #     full_cycles = (n + 1) // B
    #     remainder = (n + 1) % B
    #     sum = full_cycles * (B * (B - 1) // 2) + (remainder * (remainder - 1) // 2)
    #
    # Segment Tree details:
    #   Each node covers a range of elementary intervals.
    #   We need to support:
    #     - Range Set Update: Set the value generation rule for a range of elementary intervals.
    #       Since the rule depends on L, A, B, we store (L, A, B) in the lazy tag.
    #     - Range Sum Query: Sum the values generated by the current rule.
    #
    # Note: The problem states "Set the number of stones...". This is an assignment.
    # Previous values are overwritten.
    
    coords = set()
    queries = []
    
    for _ in range(Q):
        type_ = int(next(iterator))
        if type_ == 1:
            L = int(next(iterator))
            R = int(next(iterator))
            A = int(next(iterator))
            B = int(next(iterator))
            queries.append((type_, L, R, A, B))
            coords.add(L)
            coords.add(R + 1)
        else:
            L = int(next(iterator))
            R = int(next(iterator))
            queries.append((type_, L, R, 0, 0))
            coords.add(L)
            coords.add(R + 1)
    
    sorted_coords = sorted(list(coords))
    coord_map = {val: i for i, val in enumerate(sorted_coords)}
    
    # Number of elementary intervals
    num_intervals = len(sorted_coords) - 1
    if num_intervals <= 0:
        # No intervals, all queries return 0
        for _ in range(Q):
            pass # Just consume
        return

    # Segment Tree Arrays
    # Size: 4 * num_intervals
    tree_size = 4 * num_intervals
    tree_sum = [0] * tree_size
    lazy_L = [0] * tree_size
    lazy_A = [0] * tree_size
    lazy_B = [0] * tree_size
    lazy_valid = [False] * tree_size

    def get_sum_remainders(k_start, k_end, B):
        if k_start > k_end:
            return 0
        
        def f(n, B):
            if n < 0: return 0
            count = n + 1
            full_cycles = count // B
            rem = count % B
            return full_cycles * (B * (B - 1) // 2) + (rem * (rem - 1) // 2)
        
        return f(k_end, B) - f(k_start - 1, B)

    def push_down(node, l, r):
        if not lazy_valid[node]:
            return
        
        mid = (l + r) // 2
        left_node = 2 * node
        right_node = 2 * node + 1
        
        L_val, A_val, B_val = lazy_L[node], lazy_A[node], lazy_B[node]
        
        # Apply to left child
        lazy_valid[left_node] = True
        lazy_L[left_node] = L_val
        lazy_A[left_node] = A_val
        lazy_B[left_node] = B_val
        
        # Calculate sum for left child's range
        # Left child covers elementary intervals from index l to mid
        # These correspond to original coordinates: sorted_coords[l] to sorted_coords[mid+1]-1
        # We need to calculate the sum for each elementary interval and add them up.
        # But wait, the update rule is uniform for the whole range [L, R].
        # The sum for a specific elementary interval [s, e] (indices in sorted_coords) is:
        #   sum_{x=s}^{e} ((x - L + 1)*A) % B
        #   = A * sum_{k=s-L+1}^{e-L+1} (k % B)
        # We can precompute or compute on the fly. Since we are pushing down, we just need to update the sum.
        
        # Actually, it's better to compute the sum for the entire range covered by the child node.
        # The child node covers elementary intervals [l, mid].
        # The original coordinates for these intervals are:
        #   start_coord = sorted_coords[l]
        #   end_coord = sorted_coords[mid+1] - 1
        # The values are defined for x in [start_coord, end_coord].
        # We need sum_{x=start_coord}^{end_coord} ((x - L_val + 1) * A_val) % B
        # Let k = x - L_val + 1.
        # k_start = start_coord - L_val + 1
        # k_end = end_coord - L_val + 1
        # Total Sum = A_val * get_sum_remainders(k_start, k_end, B_val)
        
        # Update left child sum
        start_coord = sorted_coords[l]
        end_coord = sorted_coords[mid+1] - 1
        k_start = start_coord - L_val + 1
        k_end = end_coord - L_val + 1
        tree_sum[left_node] = A_val * get_sum_remainders(k_start, k_end, B_val)
        
        # Apply to right child
        lazy_valid[right_node] = True
        lazy_L[right_node] = L_val
        lazy_A[right_node] = A_val
        lazy_B[right_node] = B_val
        
        start_coord = sorted_coords[mid+1]
        end_coord = sorted_coords[r] - 1
        k_start = start_coord - L_val + 1
        k_end = end_coord - L_val + 1
        tree_sum[right_node] = A_val * get_sum_remainders(k_start, k_end, B_val)
        
        # Clear current node lazy
        lazy_valid[node] = False
        lazy_L[node] = 0
        lazy_A[node] = 0
        lazy_B[node] = 0

    def update(node, l, r, ql, qr, L_val, A_val, B_val):
        if ql > r or qr < l:
            return
        
        if ql <= l and r <= qr:
            lazy_valid[node] = True
            lazy_L[node] = L_val
            lazy_A[node] = A_val
            lazy_B[node] = B_val
            
            start_coord = sorted_coords[l]
            end_coord = sorted_coords[r+1] - 1
            k_start = start_coord - L_val + 1
            k_end = end_coord - L_val + 1
            tree_sum[node] = A_val * get_sum_remainders(k_start, k_end, B_val)
            return
        
        push_down(node, l, r)
        mid = (l + r) // 2
        update(2 * node, l, mid, ql, qr, L_val, A_val, B_val)
        update(2 * node + 1, mid + 1, r, ql, qr, L_val, A_val, B_val)
        
        tree_sum[node] = tree_sum[2 * node] + tree_sum[2 * node + 1]

    def query(node, l, r, ql, qr):
        if ql > r or qr < l:
            return 0
        
        if ql <= l and r <= qr:
            return tree_sum[node]
        
        push_down(node, l, r)
        mid = (l + r) // 2
        return query(2 * node, l, mid, ql, qr) + query(2 * node + 1, mid + 1, r, ql, qr)

    # Process queries
    results = []
    for q in queries:
        type_ = q[0]
        if type_ == 1:
            _, L, R, A, B = q
            l_idx = coord_map[L]
            r_idx = coord_map[R + 1] - 1
            # Update range [l_idx, r_idx] in the segment tree (which represents elementary intervals)
            update(1, 0, num_intervals - 1, l_idx, r_idx, L, A, B)
        else:
            _, L, R, _, _ = q
            l_idx = coord_map[L]
            r_idx = coord_map[R + 1] - 1
            # Query range [l_idx, r_idx]
            total = query(1, 0, num_intervals - 1, l_idx, r_idx)
            results.append(str(total))
    
    print('\n'.join(results))

if __name__ == '__main__':
    solve()