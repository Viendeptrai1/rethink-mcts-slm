import sys

def solve():
    input_data = sys.stdin.read().split()
    if not input_data:
        return
    A = int(input_data[0])
    B = int(input_data[1])
    C = int(input_data[2])

    remainder = A % B
    if remainder == 0:
        if C == 0:
            print("YES")
        else:
            print("NO")
    else:
        # We can generate any multiple of remainder modulo B
        # Since we can pick any number of integers, we can reach any multiple of gcd(remainder, B)
        # But since remainder and B are fixed, the set of reachable residues is {k * remainder mod B}
        # This set generates the subgroup generated by remainder in Z_B, which has size B / gcd(remainder, B)
        # However, a simpler observation: if we can pick multiple numbers, we can form any multiple of remainder.
        # The set of achievable sums mod B is { (k * remainder) % B for k >= 1 }.
        # This set is exactly the multiples of g = gcd(remainder, B) modulo B.
        # So we just need to check if C is a multiple of g.
        import math
        g = math.gcd(remainder, B)
        if C % g == 0:
            print("YES")
        else:
            print("NO")

if __name__ == "__main__":
    solve()